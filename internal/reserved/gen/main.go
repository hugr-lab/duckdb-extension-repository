// Command gen writes the pin's extension aliases (internal/reserved/aliases.txt) and DuckDB's
// built-in core and community signing keys (spec 0009) from a DuckDB checkout at the pin. The
// reserved names are the server's data since spec 0030 (kista duckdb core-extensions).
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	aliasRE = regexp.MustCompile(`\{"([a-z0-9_]+)",\s*"([a-z0-9_]+)"\}`)
	pemRE   = regexp.MustCompile(`(?s)-----BEGIN PUBLIC KEY-----\n.*?-----END PUBLIC KEY-----`)
)

func main() {
	duckdb := flag.String("duckdb", "", "a DuckDB checkout at e2e/DUCKDB_PIN")
	out := flag.String("out", "internal/reserved", "the directory of aliases.txt")
	keysOut := flag.String("keys", "internal/upstream/duckdbkeys", "the directory of DuckDB's keys")
	flag.Parse()
	if *duckdb == "" {
		flag.Usage()
		os.Exit(2)
	}
	aliases, err := aliasList(*duckdb)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "aliases.txt"), []byte(aliases), 0o644); err != nil {
		fail(err)
	}
	if err := writeKeys(*duckdb, *keysOut); err != nil {
		fail(err)
	}
}

// aliasList is the pin's internal_aliases[] (extension_alias.cpp), "alias name" per line.
func aliasList(root string) (string, error) {
	src, err := read(filepath.Join(root, "src/main/extension/extension_alias.cpp"))
	if err != nil {
		return "", err
	}
	i := strings.Index(src, "internal_aliases[]")
	j := strings.Index(src[max(i, 0):], "{nullptr, nullptr}")
	if i < 0 || j < 0 {
		return "", fmt.Errorf("internal_aliases[] not found in extension_alias.cpp")
	}
	var b strings.Builder
	b.WriteString("# Generated by make reserved (spec 0009): the pin's extension aliases. Do not edit.\n")
	for _, m := range aliasRE.FindAllStringSubmatch(src[i:i+j], -1) {
		fmt.Fprintf(&b, "%s %s\n", m[1], m[2])
	}
	if !strings.Contains(b.String(), "postgres postgres_scanner") {
		return "", fmt.Errorf("the alias list looks wrong")
	}
	return b.String(), nil
}

// writeKeys writes the pin's public_keys[] and community_public_keys[] (extension_helper.cpp) as
// core.pem and community.pem, in the pin's order.
func writeKeys(root, dir string) error {
	src, err := read(filepath.Join(root, "src/main/extension/extension_helper.cpp"))
	if err != nil {
		return err
	}
	for file, array := range map[string]string{"core.pem": "public_keys[]", "community.pem": "community_public_keys[]"} {
		i := strings.Index(src, "static const char *const "+array)
		if i < 0 {
			return fmt.Errorf("%s not found in extension_helper.cpp", array)
		}
		j := strings.Index(src[i:], "nullptr}")
		if j < 0 {
			return fmt.Errorf("the end of %s not found", array)
		}
		keys := pemRE.FindAllString(src[i:i+j], -1)
		if len(keys) == 0 {
			return fmt.Errorf("no keys in %s", array)
		}
		out := "# Generated by make reserved (spec 0009): DuckDB's " + array + " at the pin. Do not edit.\n" +
			strings.Join(keys, "\n") + "\n"
		if err := os.WriteFile(filepath.Join(dir, file), []byte(out), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

func read(path string) (string, error) {
	b, err := os.ReadFile(path)
	return string(b), err
}
