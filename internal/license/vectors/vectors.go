type gen struct {
	keys  license.Keys
	cases []Case
	names map[string]bool
	err   error
}

func (g *gen) fail(format string, args ...any) {
	g.err = errors.Join(g.err, fmt.Errorf(format, args...))
}

// add records a case with the reference verifier's answer, which must refuse it for the rule
// expected ("" for a token that is not invalid).
func (g *gen) add(name, rule, tok, ext, version string, now int64) {
	if g.names[name] {
		g.fail("duplicate case %q", name)
	}
	g.names[name] = true
	c, st, err := license.Verify(tok, g.keys, ext, version, time.Unix(now, 0))
	got := ""
	var le *license.Error
	if errors.As(err, &le) {
		got = le.Rule
	} else if err != nil {
		g.fail("%s: %v is not a rule", name, err)
	}
	if got != rule {
		g.fail("%s: refused for %q (%v), want %q", name, got, err, rule)
	}
	g.cases = append(g.cases, Case{Name: name, Token: tok, Ext: ext, Version: version, Now: now, Status: st, Rule: got, Claims: c})
}

// exactSize is a valid licence of exactly MaxSize bytes, padded with an unknown member (and, when
// the parts' lengths need it, a space in the header: no base64 has a length of 1 mod 4).
func (g *gen) exactSize(key *rsa.PrivateKey, h string) string {
	for sp := 0; sp < 3; sp++ {
		hdr := h[:len(h)-1] + rep(" ", sp) + "}"
		for n := 11000; n < 12500; n++ {
			if tok := Sign(key, hdr, base().set("pad", q(rep("x", n))).String()); len(tok) == license.MaxSize {
				return tok
			}
		}
	}
	g.fail("no padding makes a licence of exactly %d bytes", license.MaxSize)
	return ""
}

// trailingHeader is a licence whose header part ends in non-zero unused bits.
func (g *gen) trailingHeader(key *rsa.PrivateKey) string {
	h := `{"alg":"RS256","typ":"kista-license+jwt","kid":"` + Kid(&key.PublicKey) + `"`
	for pad := 0; pad < 3; pad++ {
		if hdr := h + rep(" ", pad) + "}"; len(hdr)%3 != 0 {
			in := trailingBits(b64(hdr)) + "." + b64(base().String())
			return in + "." + base64.RawURLEncoding.EncodeToString(pkcs1(key, []byte(in)))
		}
	}
	g.fail("no header length leaves unused bits")
	return ""
}

// oneMod4 is what to append to a part so that its length is 1 mod 4, which no base64 has.
func (g *gen) oneMod4(part string) string {
	return rep("A", (5-len(part)%4)%4)
}
