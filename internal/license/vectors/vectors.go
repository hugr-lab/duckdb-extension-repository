// Package vectors builds spec 0012's licence test vectors (internal/license/testdata/vectors.json)
// from the test-only keys committed beside them. Signing is plain modular arithmetic here (no
// crypto/rsa signing, which may refuse 1024-bit keys or salt at random), so the file is the same
// on every platform: a test regenerates it and fails on a difference. The C++ SDK's tests read the
// same file, so the Go and C++ verifiers agree on every token, and refuse each for the same rule.
package vectors

